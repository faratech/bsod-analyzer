// Prints bigquery/live_stats.sql: the /api/stats live aggregation (eventsQuery,
// single source of truth in server/statsBigQuery.js) wrapped in EXPORT DATA so a
// BigQuery scheduled query publishes it to Cloud Storage. Cloud Run only reads
// the exported JSON and never queries BigQuery.
//   node scripts/build-live-stats-sql.mjs > bigquery/live_stats.sql
import { eventsQuery } from '../server/statsBigQuery.js';

const project = process.env.BQ_PROJECT || 'project-bigfoot';
const bucket = process.env.STATS_BUCKET || 'project-bigfoot-bsod-stats';
const windowDays = Number(process.env.STATS_DAILY_WINDOW_DAYS || 90);
const select = eventsQuery(`${project}.bsod_stats.run_googleapis_com_stdout`).replace(/@window_days/g, String(windowDays));

process.stdout.write(`-- GENERATED by scripts/build-live-stats-sql.mjs; do not edit by hand.
-- Scheduled hourly: live stats aggregates -> gs://${bucket}/live/
EXPORT DATA OPTIONS (uri = 'gs://${bucket}/live/*.json', format = 'JSON', overwrite = true) AS
SELECT CURRENT_TIMESTAMP() AS generated_at, aggregates FROM (
${select.trim()}
);
`);
